import mongoose from "mongoose";
import { encryptField, decryptField } from "../utils/cryptoField.js";

// Module 2 (ADR Report Intake) + Module 3 (de-identification) storage.
// Enriched with ICH E2A seriousness criteria, regulatory clock tracking, causality assist, and terminologies.
const reportSchema = new mongoose.Schema(
  {
    submittedBy: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    source: { type: String, enum: ["pdf", "docx", "pasted_text", "manual_form", "fhir_r4"], required: true },
    originalFilename: { type: String },
    rawText: { type: String, required: true }, // as submitted, pre-deidentification
    deidentifiedText: { type: String }, // set once Module 3 runs
    deidentificationLog: [
      {
        type: { type: String }, // e.g. "name", "phone", "email", "address", "hospital_id"
        span: { type: String },
      },
    ],
    status: {
      type: String,
      enum: [
        "submitted", // just intake, pipeline not yet run
        "processing", // pipeline running
        "pending_review", // pipeline complete, awaiting pharmacist
        "approved",
        "rejected",
        "needs_more_info",
      ],
      default: "submitted",
    },
    summary: { type: String }, // clinical narrative generated by LLM/summarizer
    summaryModelVersion: { type: String },
    aiSummary: { type: String }, // Persisted narrative summary from AI pipeline
    patient: {
      age: { type: Number },
      sex: { type: String, enum: ["male", "female", "other", "unknown"], default: "unknown" },
      weightKg: { type: Number },
    },
    regulatoryClock: {
      days: { type: Number, enum: [7, 15] },
      deadline: { type: Date },
      isExpedited: { type: Boolean, default: false },
    },
    duplicateFlag: {
      isPotentialDuplicate: { type: Boolean, default: false },
      matchedReportId: { type: mongoose.Schema.Types.ObjectId, ref: "Report" },
      similarityScore: { type: Number },
      matchReason: { type: String },
    },
    causality: {
      naranjoScore: { type: Number },
      naranjoCategory: { type: String }, // Definite, Probable, Possible, Doubtful
      whoUmcCategory: { type: String },  // Certain, Probable, Possible, Unlikely, Conditional, Unassessable
      pharmacistConfirmed: { type: Boolean, default: false },
      pharmacistCausality: { type: String },
    },
    ichSeriousness: [
      {
        type: String,
        enum: ["death", "life_threatening", "hospitalization", "disability", "congenital_anomaly", "medically_important"],
      },
    ],
    pipelineRunId: { type: String }, // ties this report to Extraction/Classification/Retrieval/AuditLog records

    // ICH E2A Seriousness & Regulatory Clock
    ichE2ACriteria: [
      {
        type: String,
        enum: ["death", "life_threatening", "hospitalization", "disability", "congenital_anomaly", "medically_significant", "other_serious"],
      },
    ],
    isSerious: { type: Boolean, default: false },
    regulatoryClockDays: { type: Number, default: 15 },
    regulatoryDueDate: { type: Date },

    // Causality Assessment (Naranjo & WHO-UMC)
    causality: {
      naranjoScore: { type: Number },
      naranjoCategory: { type: String }, // Definite, Probable, Possible, Doubtful
      whoUmcCategory: { type: String }, // Certain, Probable, Possible, Unlikely, Conditional, Unassessable
      rationale: { type: String },
      confirmedByPharmacist: { type: Boolean, default: false },
      pharmacistNotes: { type: String },
    },

    // Standardized Regulatory Terminology
    terminology: {
      drugRxNorm: { type: mongoose.Schema.Types.Mixed },
      meddraAdverseEvents: [{ type: mongoose.Schema.Types.Mixed }],
    },

    // Citation Verification / Anti-Hallucination
    citationVerification: { type: mongoose.Schema.Types.Mixed },

    // FHIR Interoperability Metadata
    fhirMetadata: {
      resourceId: { type: String },
      subjectIdentifier: { type: String },
      recordedDate: { type: Date },
    },

    // Regulatory Gateway Transmission Tracking
    gatewayTransmission: {
      status: {
        type: String,
        enum: ["untransmitted", "pending_ack", "acknowledged", "rejected"],
        default: "untransmitted",
      },
      gateway: { type: String }, // e.g., "FDA_ESG", "EMA_EV"
      transmissionId: { type: String },
      transmittedAt: { type: Date },
      mdnStatus: { type: String },
      mdnMessage: { type: String },
      as2MessageId: { type: String },
    },
  },
  { timestamps: true }
);

// Pre-save hook: transparently encrypt rawText PHI before storing in database
reportSchema.pre("save", function (next) {
  if (this.isModified("rawText") && this.rawText) {
    this.rawText = encryptField(this.rawText);
  }
  next();
});

// Instance method to retrieve decrypted rawText for authorized clinical review
reportSchema.methods.getDecryptedRawText = function () {
  return decryptField(this.rawText);
};

export default mongoose.model("Report", reportSchema);
